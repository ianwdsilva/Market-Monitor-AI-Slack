"""Pydantic models for Market Monitor."""

from __future__ import annotations

from datetime import datetime
from enum import Enum
from typing import Dict, List, Optional

from pydantic import BaseModel, Field


class SignalDirection(str, Enum):
    """Direction of a trading signal."""

    BUY = "BUY"
    SELL = "SELL"


class PatternType(str, Enum):
    """Types of chart patterns detected."""

    GOLDEN_CROSS = "golden_cross"
    DEATH_CROSS = "death_cross"
    MACD_BULLISH_CROSS = "macd_bullish_cross"
    MACD_BEARISH_CROSS = "macd_bearish_cross"
    RSI_BULLISH_DIVERGENCE = "rsi_bullish_divergence"
    RSI_BEARISH_DIVERGENCE = "rsi_bearish_divergence"
    BOLLINGER_SQUEEZE = "bollinger_squeeze"
    SUPPORT_BOUNCE = "support_bounce"
    RESISTANCE_REJECTION = "resistance_rejection"
    VWAP_CROSS_ABOVE = "vwap_cross_above"
    VWAP_CROSS_BELOW = "vwap_cross_below"
    SAR_BULLISH_FLIP = "sar_bullish_flip"
    SAR_BEARISH_FLIP = "sar_bearish_flip"


class PatternSignal(BaseModel):
    """A detected chart pattern."""

    pattern_type: PatternType
    timestamp: datetime
    price: float
    description: str
    strength: float = Field(ge=0.0, le=1.0, description="Pattern strength/reliability")


class Signal(BaseModel):
    """A trading signal generated by a strategy."""

    ticker: str
    timestamp: datetime
    strategy_name: str
    direction: SignalDirection
    confidence: float = Field(ge=0.0, le=1.0, description="Signal confidence score")
    current_price: float
    indicators: Dict[str, float] = Field(default_factory=dict)
    patterns: List[PatternSignal] = Field(default_factory=list)
    reason: str = Field(description="Human-readable explanation of the signal")
    confirmations: int = Field(ge=0, description="Number of indicator confirmations")

    @property
    def emoji(self) -> str:
        """Get emoji for signal direction."""
        return "🟢" if self.direction == SignalDirection.BUY else "🔴"


class TradeOutcome(BaseModel):
    """Outcome of a backtested trade."""

    entry_time: datetime
    entry_price: float
    direction: SignalDirection
    exit_time_15m: Optional[datetime] = None
    exit_price_15m: Optional[float] = None
    return_15m: Optional[float] = None
    exit_time_1h: Optional[datetime] = None
    exit_price_1h: Optional[float] = None
    return_1h: Optional[float] = None
    exit_time_4h: Optional[datetime] = None
    exit_price_4h: Optional[float] = None
    return_4h: Optional[float] = None

    @property
    def is_winner_15m(self) -> Optional[bool]:
        """Check if trade was profitable at 15m mark."""
        if self.return_15m is None:
            return None
        if self.direction == SignalDirection.BUY:
            return self.return_15m > 0
        return self.return_15m < 0

    @property
    def is_winner_1h(self) -> Optional[bool]:
        """Check if trade was profitable at 1h mark."""
        if self.return_1h is None:
            return None
        if self.direction == SignalDirection.BUY:
            return self.return_1h > 0
        return self.return_1h < 0


class StrategyPerformance(BaseModel):
    """Performance metrics for a strategy on a specific ticker."""

    strategy_name: str
    ticker: str
    total_signals: int = 0
    win_rate_15m: float = 0.0
    win_rate_1h: float = 0.0
    win_rate_4h: float = 0.0
    avg_return_15m: float = 0.0
    avg_return_1h: float = 0.0
    avg_return_4h: float = 0.0
    profit_factor: float = 0.0  # gross profit / gross loss
    max_consecutive_losses: int = 0
    sharpe_ratio: float = 0.0
    outcomes: List[TradeOutcome] = Field(default_factory=list)

    @property
    def is_profitable(self) -> bool:
        """Check if strategy is profitable overall."""
        return self.win_rate_1h > 0.5 and self.profit_factor > 1.0


class BacktestResult(BaseModel):
    """Complete backtest results for all strategies on all tickers."""

    run_timestamp: datetime
    backtest_days: int
    strategies: Dict[str, Dict[str, StrategyPerformance]] = Field(
        default_factory=dict,
        description="Nested dict: strategy_name -> ticker -> performance",
    )
    best_strategy_per_ticker: Dict[str, str] = Field(
        default_factory=dict,
        description="Mapping of ticker -> best strategy name",
    )

    def get_best_strategy(self, ticker: str) -> Optional[str]:
        """Get the best performing strategy for a ticker."""
        return self.best_strategy_per_ticker.get(ticker.upper())


class AlertRecord(BaseModel):
    """Record of a sent alert for cooldown tracking."""

    ticker: str
    signal: Signal
    sent_at: datetime
    slack_response_ok: bool = True
    error_message: Optional[str] = None

    @property
    def cooldown_expires_at(self) -> datetime:
        """Calculate when cooldown expires (placeholder, uses config in practice)."""
        from datetime import timedelta
        return self.sent_at + timedelta(minutes=60)
